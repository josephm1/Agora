/* Offline OSCE through the real packaged sandbox. No source or model requests before Run. */
module.exports = async ({page,open,assert}) => {
  const fs = require('node:fs');
  const path = require('node:path');
  const template = JSON.parse(fs.readFileSync(path.join(__dirname,'../examples/interactive-templates/osce/osce.agora-template.json'),'utf8'));
  const catalogue = JSON.parse(fs.readFileSync(path.join(__dirname,'../examples/interactive-templates/osce/catalogue.json'),'utf8'));
  assert.equal(Object.values(catalogue.Medicine).flat().length,165);
  assert.equal(Object.values(catalogue.Surgery).flat().length,135);
  const originalViewport = page.viewportSize();
  await page.setViewportSize({width:360,height:900});
  let frame = await open(template.answer,false,false,{eInkMode:true,fontScale:1});
  await frame.locator('.specialties button').first().waitFor();
  assert.equal(await frame.locator('body').evaluate(el=>el.scrollWidth<=el.clientWidth),true);
  assert.equal(await frame.locator('.specialties button').count(),18);
  assert.equal(await frame.locator('input[type=search]').count(),0);
  assert.ok(await frame.locator('main').evaluate(el=>el.getBoundingClientRect().height<560));
  assert.equal(await frame.locator('#count').getAttribute('type'),'range');
  assert.equal(await frame.locator('#count').inputValue(),'12');
  assert.equal(await frame.locator('#start').isDisabled(),true);
  const sends = () => page.evaluate(()=>window.nativeEvents.filter(e=>e.method==='sendPrompt'));
  assert.equal((await sends()).length,0);
  await frame.getByRole('button',{name:'Cardiology (Medicine)',exact:true}).click();
  assert.equal(await frame.locator('.condition').count(),15);
  await frame.getByRole('button',{name:'Acute Coronary Syndrome',exact:true}).click();
  assert.equal(await frame.locator('#selection').textContent(),'Acute Coronary Syndrome');
  await frame.locator('#count').focus();
  await frame.locator('#count').press('ArrowRight');
  assert.equal(await frame.locator('#count').inputValue(),'13');
  assert.equal(await frame.locator('#count-value').textContent(),'13');
  assert.equal((await sends()).length,0);
  const report = path.join(__dirname,'../app/build/reports/interactive-templates');
  fs.mkdirSync(report,{recursive:true});
  await page.screenshot({path:path.join(report,'zero-to-finals-mobile.png'),fullPage:true});
  await frame.locator('#start').click();
  await page.waitForFunction(()=>window.nativeEvents.some(e=>e.method==='sendPrompt'));
  const prompt = (await sends())[0].value;
  assert.equal((await sends()).length,1);
  assert.ok(prompt.includes('Acute Coronary Syndrome'));
  assert.ok(prompt.includes('Questions: 13'));
  assert.ok(prompt.includes('LOCAL_SOURCE_FILE: ztf-m-cardiology-acs.md'));
  assert.ok(prompt.includes('Do not fetch websites, search the web, use MCP'));
  assert.ok(!prompt.includes('ztf-s-'));
  // Reopen saved code: no generation, defaults restored, both areas remain local.
  frame = await open(template.answer,false,false,{eInkMode:true,fontScale:1});
  await frame.locator('.specialties button').first().waitFor();
  assert.equal(await frame.locator('#count').inputValue(),'12');
  assert.equal(await frame.locator('#start').isDisabled(),true);
  await frame.getByRole('button',{name:'General Surgery (Surgery)',exact:true}).click();
  await frame.getByRole('button',{name:'Appendicitis',exact:true}).click();
  await frame.locator('#count').evaluate(el=>{el.value='40';el.dispatchEvent(new Event('input',{bubbles:true}));});
  assert.equal(await frame.locator('#count-value').textContent(),'40');
  assert.equal((await sends()).length,0);
  await frame.locator('#start').click();
  await page.waitForFunction(()=>window.nativeEvents.some(e=>e.method==='sendPrompt'));
  assert.ok((await sends())[0].value.includes('LOCAL_SOURCE_FILE: ztf-s-general-appendicitis.md'));
  assert.ok((await sends())[0].value.includes('Questions: 40'));
  await frame.locator('#random').click();
  const selected = await frame.locator('#selection').textContent();
  assert.ok(catalogue.Surgery['General Surgery'].some(topic=>topic.title===selected));
  assert.equal((await sends()).length,1);
  await frame.locator('#back').click();
  assert.equal(await frame.locator('#categories').isVisible(),true);
  assert.equal(await frame.locator('#condition-page').isVisible(),false);
  // A larger viewport uses the same saved interface, with no horizontal overflow.
  await page.setViewportSize({width:900,height:1000});
  frame = await open(template.answer,false,false,{eInkMode:false,fontScale:1});
  await frame.getByRole('button',{name:'Cardiology (Medicine)',exact:true}).click();
  await frame.getByRole('button',{name:'Acute Coronary Syndrome',exact:true}).click();
  assert.equal(await frame.locator('body').evaluate(el=>el.scrollWidth<=el.clientWidth),true);
  await page.screenshot({path:path.join(report,'zero-to-finals-desktop.png'),fullPage:true});
  await page.setViewportSize(originalViewport);
};
